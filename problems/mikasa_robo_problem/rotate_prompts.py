# Flat-observation index of the last qpos element — the 2nd parallel-gripper finger,
# which is redundant with the 1st (corr > 0.9999, so it carries ~no unique signal).
# Rotate* tasks reuse this slot to carry target_angle without changing the obs dim.
# Layout: overhead(49152) | gripper(49152) | tcp_pose(7) | qpos(9) | qvel(9) = 98329.
PROMPT_SLOT = 98319


def inject_rotate_prompt(obs, env_id, traj_index):
    """Overwrite ``obs[PROMPT_SLOT]`` with the Rotate target_angle, in place.

    ``obs`` is a flat (98329,) observation; ``traj_index`` is the original
    ``train_data_<i>`` index. No-op for non-Rotate envs (returns obs unchanged),
    so callers can invoke it unconditionally.
    """
    prompts = ROTATE_PROMPTS.get(env_id)
    if prompts is not None:
        obs[PROMPT_SLOT] = prompts[traj_index]
    return obs
