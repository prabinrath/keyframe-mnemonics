"""
Visualize the LTMB policy dataset generated by generate_policy_dataset.py.

Usage:
    python visualize/visualize_minigrid_policy_dataset.py --h5_path checkpoints/ltmb_Hallway_<TAG>/policy_dataset/ltmb_Hallway_policy_dataset.h5
"""
import argparse
import numpy as np
import h5py
import matplotlib.pyplot as plt
from minigrid.core.grid import Grid


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='LTMB-VisualizePolicyDataset')
    parser.add_argument('--h5_path', type=str, required=True, help='Path to the policy dataset H5 file')
    parser.add_argument('--start', type=int, default=0, help='Start sample index')
    parser.add_argument('--num_samples', type=int, default=None, help='Number of samples to visualize')
    args = parser.parse_args()

    with h5py.File(args.h5_path, 'r') as f:
        n_samples, flat_dim = f['inputs'].shape
        total_slots = flat_dim // 148
        print(f"Dataset: {n_samples} samples, {total_slots} buffer slots, horizon={f['outputs'].shape[1]}")

        end = args.start + args.num_samples if args.num_samples is not None else n_samples

        plt.ion()
        fig, ax = plt.subplots(1, 1, figsize=(15, 4))
        ax.axis('off')

        for i in range(args.start, end):
            input_data = f['inputs'][i]
            buffer_imgs = input_data.reshape(total_slots, -1)[:,:147]
            buffer_imgs = buffer_imgs.reshape(total_slots, 7, 7, 3)
            directions = input_data.reshape(total_slots, -1)[:,147]
            target = f['outputs'][i].astype(int)
            rendered = []
            for slot in range(total_slots):
                decoded_grid, _ = Grid.decode(buffer_imgs[slot])
                rendered.append(decoded_grid.render(tile_size=32, agent_pos=None, agent_dir=None))
            horizontal = np.concatenate(rendered, axis=1)

            ax.clear()
            ax.imshow(horizontal)
            ax.set_title(f"Sample {i}/{n_samples}  | directions: {directions} | target actions: {target}")
            ax.axis('off')
            plt.pause(0.1)

        plt.ioff()
        plt.close()
