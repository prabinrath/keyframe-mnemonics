"""
Stage 3: train the policy model via behavior cloning on the policy dataset
generated by a frozen selector.

The backend is dispatched on config `pipeline.policy_dataset`:
  - "h5": flat (buffer, action) pairs in HDF5 (synthetic and grid domains).
  - "lerobot": LeRobot video dataset with dict observations (robot domains).

Usage:
    python -m keyframe_mnemonics.train_policy --experiment_name tmaze --selector_checkpoint tmaze_<TAG>
"""
import argparse
import os
import glob
import yaml
import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader, WeightedRandomSampler
from pathlib import Path
from datetime import datetime
import wandb

from models import model_dict
from problems import problem_dict
from keyframe_mnemonics.memory_manager import MemoryManager
from common.helpers import set_seeds, parse_experiment_name, get_problem_type_and_conf_path, stage_dir, tee_stdout


class PolicyDataset(Dataset):
    """Stage-3 dataset wrapping a MemoryManager of (buffer, action) pairs
    produced by rolling out a frozen selector (in-memory or H5-backed)."""

    def __init__(self, memory, action_dim):
        self.action_dim = action_dim
        self.memory = memory

    def __len__(self):
        return len(self.memory)

    def __getitem__(self, idx):
        return self.memory.read(idx)

    def get_sample_weights(self):
        actions = self.memory.outputs_array()[:, 0].astype(int)
        counts = np.bincount(actions, minlength=self.action_dim)
        return torch.from_numpy(1.0 / counts[actions].clip(min=1)).float()

    def close(self):
        self.memory.close()


def _resolve_run_folder(experiment_name, selector_checkpoint, resume_checkpoint):
    """The policy stage writes into the same run folder as its upstream selector.

    Falls back to the resume checkpoint's run folder, or mints a fresh run folder
    when the policy stage is run in isolation.
    """
    if selector_checkpoint:
        return selector_checkpoint
    if resume_checkpoint:
        return resume_checkpoint
    tag = datetime.now().strftime("%Y%m%d_%H%M%S")
    return f"{experiment_name}_{tag}"


def _create_policy_checkpoint_dir(run_folder, path_prefix, config):
    """Create the policy stage subfolder inside the run folder and save the config."""
    checkpoint_path = Path(stage_dir(path_prefix, run_folder, "policy"))
    checkpoint_path.mkdir(parents=True, exist_ok=True)
    tee_stdout(checkpoint_path / "train.log")
    with open(checkpoint_path / "config.yaml", 'w') as f:
        yaml.dump(config, f, default_flow_style=False)
    print(f"Checkpoint directory: {checkpoint_path}")
    return checkpoint_path


