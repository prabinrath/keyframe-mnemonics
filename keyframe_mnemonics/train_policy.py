# Flat-H5 backend (synthetic and grid domains)
# ---------------------------------------------------------------------------

def _train_flat_policy(experiment_name, problem_type, config, selector_checkpoint, seed, device):
    path_prefix = config.get("path_prefix", "")
    policy_config = config["policy"]
    model_config = policy_config["model_kwargs"]
    problem_config = dict(config["problem"])
    problem_config.update(config.get("policy_problem_override", {}))
    action_dim = problem_config["action_dim"]

    # Policy stage subfolder inside the run folder (shared with the selector stage)
    run_folder = _resolve_run_folder(experiment_name, selector_checkpoint, "")

    # Acquire the dataset by rolling out the frozen selector. cache_path "" keeps it
    # in RAM; anything else writes/streams an H5 into the run folder.
    cache_path = policy_config.get("cache_path", "")
    generate = problem_dict.get(problem_type).get("policy_dataset_generator")
    if cache_path:
        cache_path = stage_dir(path_prefix, run_folder, "policy_dataset")
        h5_path = os.path.join(cache_path, f"{experiment_name}_policy_dataset.h5")
        if os.path.exists(h5_path):
            print(f"Using existing policy dataset: {h5_path}")
            memory = MemoryManager.open(h5_path)
        else:
            memory = generate(selector_checkpoint, cache_path=cache_path, seed=seed)
    else:
        print("Generating policy dataset in memory")
        memory = generate(selector_checkpoint, cache_path="", seed=seed)
    dataset = PolicyDataset(memory, action_dim=action_dim)
    print(f"Dataset size: {len(dataset)}")

    balance_sampler = policy_config.get("balance_sampler", False)
    sample_weights = dataset.get_sample_weights() if balance_sampler else None

    if balance_sampler:
        sampler = WeightedRandomSampler(sample_weights, num_samples=len(dataset), replacement=True)
        print("Weighted sampler enabled")

    # In-RAM data -> load in the main process; streaming from H5 -> persistent
    # workers to hide read latency.
    stream = memory.use_h5
    dataloader = DataLoader(
        dataset,
        batch_size=policy_config.get("batch_size", 256),
        sampler=sampler if balance_sampler else None,
        shuffle=not balance_sampler,
        num_workers=4 if stream else 0,
        persistent_workers=stream,
    )

    # Model
    policy_class = model_dict.get(problem_type).get("policy")
    if policy_class is None:
        raise ValueError(f"No policy model found for problem_type: {problem_type}")
    model = policy_class(output_dim=action_dim, device=device, **model_config).to(device)
    print(f"Policy parameters: {sum(p.numel() for p in model.parameters()):,}")

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=policy_config.get("learning_rate", 1e-3),
        weight_decay=policy_config.get("weight_decay", 0.0),
    )

    checkpoint_path = _create_policy_checkpoint_dir(run_folder, path_prefix, config)

    # Optional policy validation + early stopping (mirrors the lerobot backend).
    if config.get("logging", False):
        wandb.init(project="keyframe_mnemonics", name=f"{run_folder}_policy", group=run_folder, job_type="policy", config=config, tags=[experiment_name])

    policy_evaluator = None
    eval_fn = None
    evaluator_config = config.get("policy_evaluator")
    if evaluator_config is not None:
        if not selector_checkpoint:
            raise ValueError("selector_checkpoint is required when policy_evaluator config is present")
        from rollout import eval_dict
        eval_fn_getter = eval_dict.get(problem_type)
        policy_evaluator_class = problem_dict.get(problem_type).get("policy_evaluator")
        if not eval_fn_getter or not policy_evaluator_class:
            raise ValueError(f"No eval_fn or policy_evaluator registered for problem_type: {problem_type}")
        eval_fn = eval_fn_getter()
        policy_evaluator = policy_evaluator_class(**evaluator_config)
        print("Policy evaluator initialized.")

    training_steps = policy_config.get("training_steps", 5000)
    save_interval = policy_config.get("save_interval", 1000)

    model.train()
    dataloader_iter = iter(dataloader)
    losses = []
    log_interval = max(1, training_steps // 20)
    for step in range(training_steps):
        try:
            buf, tgt = next(dataloader_iter)
        except StopIteration:
            dataloader_iter = iter(dataloader)
            buf, tgt = next(dataloader_iter)

        buf, tgt = buf.to(device), tgt.to(device)
        optimizer.zero_grad()
        loss = model.compute_loss(buf, tgt)
        loss.backward()
        optimizer.step()
        losses.append(loss.item())

        if (step + 1) % log_interval == 0:
            print(f"Step {step + 1}/{training_steps} | loss: {sum(losses) / len(losses):.4f}")
            losses.clear()

        if (step + 1) % save_interval == 0:
            ckpt = checkpoint_path / f"{experiment_name}_policy_{step + 1}.pth"
            torch.save(
                {"model_state_dict": model.state_dict(), "optimizer_state_dict": optimizer.state_dict()},
                ckpt,
            )
            print(f"Saved: {ckpt}")

            if policy_evaluator is not None:
                model.eval()
                converged = policy_evaluator.evaluate(eval_fn, run_folder, step + 1)
                model.train()
                if converged:
                    print(f"Early stopping at step {step + 1}: validation threshold achieved.")
                    break

    if training_steps % save_interval != 0:
        final = checkpoint_path / f"{experiment_name}_policy_{training_steps}.pth"
        torch.save(
            {"model_state_dict": model.state_dict(), "optimizer_state_dict": optimizer.state_dict()},
            final,
        )
        print(f"Final model saved: {final}")

    dataset.close()
    if wandb.run is not None:
        wandb.finish()
    print("Policy training complete.")
    return run_folder


